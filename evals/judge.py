"""LLM-as-judge for evaluating generated demographic reports."""

import json
from typing import Any

from langchain_anthropic import ChatAnthropic
from langchain_core.callbacks import get_usage_metadata_callback
from langchain_core.messages import HumanMessage
from pydantic import BaseModel, Field

from src.core.config import get_settings
from src.core.logging import get_logger, timed
from src.schemas.report import Report

logger = get_logger(__name__)

# Truncation limits keep the judge prompt small while preserving enough data
# for plausibility checks
MAX_CATEGORICAL_POINTS = 5
MAX_BUBBLE_POINTS = 8


class JudgeScores(BaseModel):
    """Structured rubric scores for a generated report (1-10 scales)."""

    overall_quality: int = Field(
        ge=1, le=10, description="Overall usefulness of the report for this business"
    )
    section_relevance: int = Field(
        ge=1, le=10, description="How relevant the sections are to the business brief"
    )
    narrative_quality: int = Field(
        ge=1, le=10, description="Clarity and insight of the executive narrative"
    )
    data_plausibility: int = Field(
        ge=1, le=10, description="Whether the numbers shown are plausible for the geographies"
    )
    visualization_appropriateness: int = Field(
        ge=1, le=10, description="Whether chart types fit the data they present"
    )
    tool_selection_relevance: int = Field(
        ge=1, le=10, description="Whether the chosen demographic metrics match the business's ideal customer"
    )
    reasoning: str = Field(description="Brief justification citing specific sections")


JUDGE_PROMPT = """
You are grading a demographic site-selection report generated by an AI \
agent for a prospective business owner. Score it 1-10 on each rubric dimension.

Rubric:
- overall_quality: Would this report actually help the owner pick a location?
- section_relevance: Do the sections analyze demographics that matter for THIS business? \
Penalize sections irrelevant to the brief.
- narrative_quality: Is the executive narrative specific, accurate to the data shown, and \
actionable (not generic filler)?
- data_plausibility: Are the values plausible for the geographies shown (e.g., incomes, \
percentages sum sensibly, no absurd outliers)?
- visualization_appropriateness: Do chart types fit the data (bar/pie for categorical \
comparisons, violin/histogram for distributions, bubble for multi-dimensional)?
- tool_selection_relevance: Did the agent pick the right demographic metrics to query for \
this business's ideal customer? Penalize obviously missing or mismatched metrics.

Be strict: 5 means mediocre, 8+ means genuinely presentation-ready.

## Business Brief
{brief}

## Generated Report (data arrays truncated for brevity)
{report_json}
"""


def condense_report(report: Report) -> dict[str, Any]:
    """Shrink a Report dict for the judge prompt.

    Keeps all titles/descriptions/narrative/summary stats; truncates bulky
    per-row data arrays so the prompt stays small.
    """
    data = report.model_dump()

    def condense_viz(viz: dict[str, Any]) -> None:
        if viz.get("categorical_data"):
            viz["categorical_data"] = viz["categorical_data"][:MAX_CATEGORICAL_POINTS]
        if viz.get("bubble_data"):
            points = viz["bubble_data"][:MAX_BUBBLE_POINTS]
            for p in points:
                p.pop("metadata", None)
            viz["bubble_data"] = points
        if viz.get("distribution_data"):
            values = [p["value"] for p in viz["distribution_data"]]
            viz["distribution_data"] = {
                "note": "distribution body omitted",
                "point_count": len(values),
                "min": min(values),
                "max": max(values),
            }

    summary_bubble = data.get("summary", {}).get("opportunity_bubble_chart")
    if summary_bubble:
        condense_viz(summary_bubble)
    for section in data.get("sections", []):
        for viz in section.get("visualizations", []):
            condense_viz(viz)

    return data


async def judge_report(brief: str, report: Report) -> tuple[JudgeScores, dict[str, int]]:
    """Score a report against its business brief.

    Returns the scores plus the judge's own token usage (kept separate from
    the agent's token metrics).
    """
    model_id = get_settings().model.split(":", 1)[-1]  # "provider:model-id" -> model-id
    llm = ChatAnthropic(model=model_id)
    judge_llm = llm.with_structured_output(JudgeScores)

    prompt = JUDGE_PROMPT.format(
        brief=brief,
        report_json=json.dumps(condense_report(report), indent=2, default=str),
    )

    with get_usage_metadata_callback() as cb:
        with timed("llm:judge.score"):
            scores: JudgeScores = await judge_llm.ainvoke([HumanMessage(content=prompt)])

    usage = {"input_tokens": 0, "output_tokens": 0, "total_tokens": 0}
    for model_usage in cb.usage_metadata.values():
        usage["input_tokens"] += model_usage.get("input_tokens", 0)
        usage["output_tokens"] += model_usage.get("output_tokens", 0)
        usage["total_tokens"] += model_usage.get("total_tokens", 0)

    logger.info(
        f"judge_report: overall={scores.overall_quality}, "
        f"tool_relevance={scores.tool_selection_relevance}, tokens={usage['total_tokens']}"
    )
    return scores, usage
